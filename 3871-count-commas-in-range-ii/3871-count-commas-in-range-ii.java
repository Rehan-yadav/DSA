class Solution {
    public long countCommas(long n) {
        long ans=0;
        if(n<1000) return 0;
        else if(n>=1000 && n<=999999){
            return n-999;
        }
        else if(n>=1000000 && n<=999999999){
            ans=999999-999+(n-999999)*2;
            return ans;
        }
        else if(n>=1000000000 && n<=999999999999L){
            ans=999999-999+(999999999-999999)*2+(n-999999999)*3;
            return ans;
        }
        else if(n>=1000000000000L && n<=999999999999999L){
            ans=999999-999+(999999999-999999)*2+(999999999999L-999999999)*3+(n-999999999999L)*4;
            return ans;
        }
        else{
            ans=999999-999+(999999999-999999)*2+(999999999999L-999999999)*3+(999999999999999L-999999999999L)*4+(n-999999999999999L)*5;
            return ans;
        }
        
    }
}